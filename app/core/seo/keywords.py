"""Извлечение поисковых ключей из текста поста — без LLM.

Зачем детерминированно: ключи считаются на КАЖДУЮ публикацию (посты, фильмы, клипы),
а лимит Groq на 70B-модели и так впритык. Частотный разбор с отсевом стоп-слов даёт
для наших тем (кино, новости, музыка) результат не хуже, чем вызов модели, и его
видно в тесте.

Два разных сорта ключей, и путать их нельзя:

* **сущности** (`extract_entities`) — имена собственные: «Роберт Дауни», «Ростов».
  Это то, что человек РЕАЛЬНО набирает в поиске. Идут в теги и в начало описания.
* **ключевые слова** (`extract_keywords`) — частотные значимые слова текста. Дают
  тематический хвост описания, по одиночке ищутся редко.
"""
from __future__ import annotations

import re
from collections import Counter

# Служебные слова русского и английского: сами по себе не ищутся, а частоту забивают.
# Список намеренно короткий — только реально высокочастотное; длинный словарь тут не
# окупается, лишнее слово в хвосте описания не вредит, а вот выброшенное имя — вредит.
STOPWORDS: frozenset[str] = frozenset(
    """
    и в во не что он на я с со как а то все она так его но да ты к у же вы за бы по
    только ее мне было вот от меня еще нет о из ему теперь когда даже ну вдруг ли если
    уже или ни быть был него до вас нибудь опять уж вам ведь там потом себя ничего ей
    может они тут где есть надо ней для мы тебя их чем была сам чтоб без будто чего раз
    тоже себе под будет ж тогда кто этот того потому этого какой совсем ним здесь этом
    один почти мой тем чтобы нее сейчас были куда зачем всех никогда можно при наконец
    два об другой хоть после над больше тот через эти нас про всего них какая много
    разве три эту моя впрочем свою этой перед иногда лучше чуть том нельзя такой им
    более всегда конечно всю между это весь эта эти этих также очень свои своих который
    которая которые которых своей нашего наших году года год лет также кроме однако
    the a an and or of to in on for with at by from is are was were be been it this that
    """.split()
)

# Слова-приманки, которые часто попадают в текст и портят теги: они не про тему.
JUNK_KEYWORDS: frozenset[str] = frozenset(
    """
    подписывайся подписывайтесь канал телеграм телеграмм телега ссылка ссылке смотреть
    читать подробнее комментарии комментах источник реклама подписка бесплатно скачать
    """.split()
)

_WORD = re.compile(r"[А-Яа-яЁёA-Za-z][А-Яа-яЁёA-Za-z\-]{2,}")
# Имя собственное: слово с большой буквы, дальше могут идти ещё такие же («Роберт Дауни
# Младший»). Дефисные фамилии («Джонсон-Смит») ловятся тем же классом символов.
#
# Пробел и табуляция, а НЕ \s: перенос строки — это граница. Иначе заголовок и тело
# поста склеивались в одно «имя»: «Дроны атаковали Ростов\nБеспилотники…» давало тег
# #ростов_беспилотники, которого никто никогда не искал.
_ENTITY = re.compile(r"[А-ЯЁA-Z][а-яёa-z\-]{2,}(?:[ \t]+[А-ЯЁA-Z][а-яёa-z\-]{2,}){0,3}")
# Начало предложения: там заглавная буква не значит имя собственное.
_SENTENCE_START = re.compile(r"(?:^|[.!?…]\s+|\n\s*)$")

MIN_WORD_LENGTH = 4


def normalize(word: str) -> str:
    return word.strip().strip("-").lower().replace("ё", "е")


def extract_keywords(text: str, limit: int = 12) -> list[str]:
    """Частотные значимые слова текста, от самого частого к редкому.

    Порядок внутри одной частоты — порядок первого появления в тексте (Counter в
    Python это гарантирует), поэтому результат не «плавает» между запусками."""
    counter: Counter[str] = Counter()
    for match in _WORD.finditer(text):
        word = normalize(match.group())
        if len(word) < MIN_WORD_LENGTH or word in STOPWORDS or word in JUNK_KEYWORDS:
            continue
        counter[word] += 1
    return [word for word, _ in counter.most_common(limit)]


def extract_entities(text: str, limit: int = 6) -> list[str]:
    """Имена собственные в порядке появления, без повторов.

    Слово в начале предложения пропускаем: там заглавная буква — правило орфографии,
    а не признак имени. Из-за этого имя, стоящее первым словом предложения, теряется —
    осознанный размен: ложное «Сегодня» в теге канала выглядит хуже, чем пропущенное
    имя, которое почти всегда встречается в тексте ещё раз."""
    seen: set[str] = set()
    entities: list[str] = []
    for match in _ENTITY.finditer(text):
        words = match.group().split()
        if _SENTENCE_START.search(text[: match.start()]):
            # Первое слово предложения отбрасываем, но НЕ всё совпадение: во фразе
            # «Губернатор Василий Голубев сообщил…» заглавная у «Губернатор» — правило
            # орфографии, а имя стоит следом. Раньше терялось и оно.
            words = words[1:]
        if not words:
            continue
        phrase = " ".join(words)
        key = normalize(phrase)
        if key in seen or all(normalize(w) in STOPWORDS for w in phrase.split()):
            continue
        seen.add(key)
        entities.append(phrase)
        if len(entities) >= limit:
            break
    return entities
