"""Чистка артефактов генерации маленьких моделей: llama-3.1-8b-instant иногда
вставляет одиночные символы из другого алфавита (катакана/иероглифы) внутрь
русского слова — токенизатор путает визуально похожие токены на редких именах
(например "Мютцинец" -> "Мュцениц"). Русский текст не должен содержать эти скрипты.
"""
from __future__ import annotations

import re

_FOREIGN_SCRIPT_PATTERN = re.compile(
    "["
    "぀-ゟ"  # хирагана
    "゠-ヿ"  # катакана
    "一-鿿"  # китайские/японские иероглифы (CJK)
    "가-힣"  # хангыль (корейский)
    "]"
)


def strip_foreign_script_artifacts(text: str) -> str:
    return _FOREIGN_SCRIPT_PATTERN.sub("", text)
